const BY_ID = new Map(CATALOG.map((product) => [product.id, product]));

export function getProduct(id: string): Product | undefined {
  return BY_ID.get(id);
}

export function productsByCategory(category: CatalogCategory): Product[] {
  return CATALOG.filter((product) => product.category === category);
}

/** Items YouCam can actually render, used to keep the deterministic filter honest. */
export function vtoCapableProducts(): Product[] {
  return CATALOG.filter((product) => product.vtoCategory !== null);
}

